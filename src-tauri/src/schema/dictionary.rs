pub fn generate_json_dictionary(tree: &SchemaTree, conn_name: &str, driver: &str) -> String {
    let now = Local::now().format("%Y-%m-%d %H:%M:%S").to_string();
    let payload = serde_json::json!({
        "generatedAt": now,
        "generator": "FugDB 1-Click Data Dictionary",
        "connectionName": conn_name,
        "driver": driver,
        "database": tree.current_database,
        "stats": {
            "totalTables": tree.tables.len(),
            "totalColumns": tree.tables.iter().map(|t| t.columns.len()).sum::<usize>(),
            "totalRelations": tree.relations.len(),
        },
        "tables": tree.tables,
        "relations": tree.relations,
    });

    serde_json::to_string_pretty(&payload).unwrap_or_else(|_| "{}".into())
}
