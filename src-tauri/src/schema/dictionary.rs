use chrono::Local;
use crate::models::schema::SchemaTree;

pub fn generate_markdown_dictionary(tree: &SchemaTree, conn_name: &str, driver: &str) -> String {
    let now = Local::now().format("%Y-%m-%d %H:%M:%S").to_string();
    let total_tables = tree.tables.len();
    let total_relations = tree.relations.len();
    let total_columns: usize = tree.tables.iter().map(|t| t.columns.len()).sum();

    let mut md = String::new();

    // 1. Header
    md.push_str(&format!("# 📚 Database Schema Documentation: {}\n\n", conn_name));
    md.push_str("> **Generated by FugDB 1-Click Data Dictionary Engine**  \n");
    md.push_str(&format!(
        "> **Database:** `{}` | **Driver Engine:** `{}` | **Generated on:** `{}`  \n",
        tree.current_database, driver, now
    ));
    md.push_str(&format!(
        "> **Summary:** `{} Tables / Views` • `{} Columns` • `{} Foreign Key Relations`\n\n",
        total_tables, total_columns, total_relations
    ));
    md.push_str("---\n\n");

    // 2. Table of Contents
    md.push_str("## 📑 Table of Contents\n\n");
    for (idx, tbl) in tree.tables.iter().enumerate() {
        let full_name = format!("{}.{}", tbl.schema, tbl.name);
        let slug = full_name.replace('.', "").to_lowercase();
        let rows_badge = match tbl.row_count_estimate {
            Some(c) => format!("~{} rows", c),
            None => "table".into(),
        };
        md.push_str(&format!(
            "{}. [{}] (#{}) — *{} ({})*\n",
            idx + 1,
            full_name,
            slug,
            tbl.table_type,
            rows_badge
        ));
    }
    md.push_str("\n---\n\n");

    // 3. Detailed Tables Section
    md.push_str("## 🗄️ Tables & Entities\n\n");
    for tbl in &tree.tables {
        let full_name = format!("{}.{}", tbl.schema, tbl.name);
        let slug = full_name.replace('.', "").to_lowercase();
        let rows_str = match tbl.row_count_estimate {
            Some(c) => format!("~{} rows", c),
            None => "N/A".into(),
        };

        md.push_str(&format!("<a id=\"{}\"></a>\n\n", slug));
        md.push_str(&format!("### `{}`\n\n", full_name));
        md.push_str(&format!("* **Schema:** `{}`\n", tbl.schema));
        md.push_str(&format!("* **Type:** `{}`\n", tbl.table_type.to_uppercase()));
        md.push_str(&format!("* **Estimated Row Count:** `{}`\n", rows_str));
        md.push_str(&format!("* **Total Columns:** `{}`\n\n", tbl.columns.len()));

        md.push_str("| # | Column Name | Data Type | Key | Nullable | Notes |\n");
        md.push_str("|---|---|---|---|---|---|\n");

        for (c_idx, col) in tbl.columns.iter().enumerate() {
            let key_badge = if col.is_primary_key && col.is_foreign_key {
                "🔑 PK, 🔗 FK"
            } else if col.is_primary_key {
                "🔑 PK"
            } else if col.is_foreign_key {
                "🔗 FK"
            } else {
                "-"
            };

            let null_str = if col.nullable { "✅ NULL" } else { "❌ NOT NULL" };
            
            // Check if column is a foreign key to find reference target
            let fk_target = tree.relations.iter().find(|r| {
                (r.from_table == tbl.name || r.from_table == full_name) && r.from_column == col.name
            });

            let notes = match fk_target {
                Some(rel) => format!("References `{}.{}`", rel.to_table, rel.to_column),
                None => {
                    if col.is_primary_key {
                        "Primary Key identifier".into()
                    } else {
                        "-".into()
                    }
                }
            };

            md.push_str(&format!(
                "| {} | **`{}`** | `{}` | {} | {} | {} |\n",
                c_idx + 1,
                col.name,
                col.data_type,
                key_badge,
                null_str,
                notes
            ));
        }

        // Table specific foreign keys
        let table_fks: Vec<_> = tree.relations.iter().filter(|r| {
            r.from_table == tbl.name || r.from_table == full_name
        }).collect();

        if !table_fks.is_empty() {
            md.push_str("\n**Foreign Key Constraints:**\n\n");
            for fk in table_fks {
                md.push_str(&format!(
                    "- `{}.{}` ➔ `{}.{}` *({})*\n",
                    tbl.name, fk.from_column, fk.to_table, fk.to_column, fk.id
                ));
            }
        }

        md.push_str("\n[⬆ Back to Top](#table-of-contents)\n\n---\n\n");
    }

    // 4. Global Entity Relationships
    if !tree.relations.is_empty() {
        md.push_str("## 🔗 Global Entity Relationships\n\n");
        md.push_str("| Constraint ID | Source Table & Column | Target Table & Column |\n");
        md.push_str("|---|---|---|\n");
        for rel in &tree.relations {
            md.push_str(&format!(
                "| `{}` | `{}.{}` | `{}.{}` |\n",
                rel.id, rel.from_table, rel.from_column, rel.to_table, rel.to_column
            ));
        }
        md.push_str("\n---\n\n");
    }

    md.push_str("\n*Generated with ❤️ by [FugDB](https://fugdb.dev) — Ultra-Fast Multi-Database Client*\n");
    md
}

